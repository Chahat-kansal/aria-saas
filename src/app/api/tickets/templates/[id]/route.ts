export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'
export const maxDuration = 30

import { NextResponse } from 'next/server'
import { createServerSupabaseClient } from '@/lib/supabase-server'
import { supabaseAdmin } from '@/lib/supabase-admin'
import { withErrorCapture } from '@/lib/api/with-error-capture'

type Params = { params: Promise<{ id: string }> | { id: string } }

async function getBid(supabase: ReturnType<typeof createServerSupabaseClient>, userId: string): Promise<string | null> {
  const { data: active } = await supabase.from('user_active_business').select('business_id').eq('user_id', userId).maybeSingle()
  if (active?.business_id) return active.business_id as string
  const { data } = await supabase.from('businesses').select('id').eq('user_id', userId).eq('is_active', true).limit(1).maybeSingle()
  return data?.id ?? null
}

async function _PUT(req: Request, { params }: Params) {
  const { id } = 'then' in params ? await params : params
  const supabase = createServerSupabaseClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  const bid = await getBid(supabase, user.id)
  if (!bid) return NextResponse.json({ error: 'No business' }, { status: 400 })
  const body = await req.json() as Record<string, unknown>
  const { data, error } = await supabaseAdmin.from('pos_shelf_ticket_templates')
    .update({ ...body, updated_at: new Date().toISOString() })
    .eq('id', id).eq('business_id', bid)
    .select('*').single()
  if (error) return NextResponse.json({ error: error.message }, { status: 500 })
  // One default per business — unset the others.
  if (body.is_default === true) {
    await supabaseAdmin.from('pos_shelf_ticket_templates').update({ is_default: false }).eq('business_id', bid).neq('id', id)
  }
  return NextResponse.json({ template: data })
}

async function _DELETE(_req: Request, { params }: Params) {
  const { id } = 'then' in params ? await params : params
  const supabase = createServerSupabaseClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  const bid = await getBid(supabase, user.id)
  if (!bid) return NextResponse.json({ error: 'No business' }, { status: 400 })
  const { error } = await supabaseAdmin.from('pos_shelf_ticket_templates')
    .delete().eq('id', id).eq('business_id', bid)
  if (error) return NextResponse.json({ error: error.message }, { status: 500 })
  return NextResponse.json({ ok: true })
}

export const PUT = withErrorCapture('tickets/templates/[id]', _PUT)
export const DELETE = withErrorCapture('tickets/templates/[id]', _DELETE)
